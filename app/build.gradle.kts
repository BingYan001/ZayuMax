// ---- 发布签名：CI 从 GitHub Secrets 注入，本地（没有这些变量时）构建未签名包 ----
// 四项环境变量齐备且证书文件真实存在，才注册 release 签名配置：
//   ZAYU_KEYSTORE_FILE      证书文件路径（.github/workflows/build-apk.yml 把 secrets.KEYSTORE_BASE64 解码到 $RUNNER_TEMP）
//   ZAYU_KEYSTORE_PASSWORD  密钥库口令
//   ZAYU_KEY_ALIAS          密钥别名
//   ZAYU_KEY_PASSWORD       密钥口令
// 缺任意一项（本地开发、ci.yml 的编译校验）⇒ release 的 signingConfig 为 null，
// 产物是 app-release-unsigned.apk，本地不需要任何配置就能 `assembleRelease`；
// 想在本地出正式签名包，自己导出这四个变量再构建即可（证书别提交进仓库，.gitignore 已挡 *.jks）。
val releaseKeystorePath: String? = System.getenv("ZAYU_KEYSTORE_FILE")?.takeIf { it.isNotBlank() }
val releaseSigningReady: Boolean = releaseKeystorePath != null &&
    file(releaseKeystorePath).isFile &&
    !System.getenv("ZAYU_KEYSTORE_PASSWORD").isNullOrBlank() &&
    !System.getenv("ZAYU_KEY_ALIAS").isNullOrBlank() &&
    !System.getenv("ZAYU_KEY_PASSWORD").isNullOrBlank()

// ---- 杂鱼Max 专属本地签名（密钥放仓库外，永不进源码包）----
// 查找顺序（命中第一个存在的即用）：
//   1) 环境变量 ZAYUMAX_KEYSTORE_PROPERTIES 指向的属性文件；
//   2) 仓库根目录 keystore.properties；
//   3) 仓库上级目录 .signing/keystore.properties（默认位置：源码包解压后天然不含它）。
// 都找不到 ⇒ localSigningReady = false：debug 回退仓库自带 debug.keystore、release 产物不签名，
// 保证任何拿到源码的人直接 assembleDebug 就能跑，不需要任何额外配置。
val localKeystoreProps: Properties? = run {
    val candidates = listOfNotNull(
        System.getenv("ZAYUMAX_KEYSTORE_PROPERTIES")?.takeIf { it.isNotBlank() }?.let { rootProject.file(it) },
        rootProject.file("keystore.properties").takeIf { it.isFile },
        rootProject.file("../.signing/keystore.properties").takeIf { it.isFile }
    )
    val propsFile = candidates.firstOrNull { it.isFile } ?: return@run null
    val props = Properties()
    // ⚠️ 必须用 load(Reader)：load(InputStream) 按 ISO-8859-1 解码，会把路径里的中文（如「AI创作文件」）
    //    解成乱码，导致后续 file(storeFile).isFile == false、签名配置被静默判定为「不可用」。
    propsFile.reader(Charsets.UTF_8).use { reader -> props.load(reader) }
    props
}
val localSigningReady: Boolean = localKeystoreProps?.let { p ->
    p.getProperty("storeFile")?.let { file(it).isFile } == true &&
        !p.getProperty("storePassword").isNullOrBlank() &&
        !p.getProperty("keyAlias").isNullOrBlank() &&
        !p.getProperty("keyPassword").isNullOrBlank()
} == true

// 构建时自证：一眼看出这次到底用了哪把钥匙（缺配置时不报错、静默回退是最难查的坑）
logger.lifecycle(
    if (localSigningReady) "杂鱼Max 签名：已启用专属密钥 ${localKeystoreProps?.getProperty("storeFile")}"
    else "杂鱼Max 签名：未找到可用的 keystore.properties → debug 回退仓库 debug.keystore，release 产出未签名包"
)

android {
    namespace = "com.zayu.app"
    compileSdk = 36

    defaultConfig {
        // 杂鱼Max：独立 applicationId，可与官方「杂鱼」共存安装、互不覆盖。
        // namespace 已随项目改名一并改为 com.zayu.app（源文件目录同步搬移 + package/import 全量替换）。
        applicationId = "com.zayu.max"
        // minSdk 24：AGP 8.13 的 D8 在 minSdk < 24 时必须脱糖接口静态方法，它把接口的 $default 桥方法
        // （如 RowScope.weight$default）搬进 $-CC 伴生类，却不改写第三方库字节码里的调用点，
        // 未混淆（debug）的包渲染 README 表格时必崩 NoSuchMethodError；24 起系统原生支持，不再脱糖。
        minSdk = 24
        targetSdk = 34
        versionCode = 36
        versionName = "1.3.16"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        getByName("debug") {
            storeFile = file("../debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        // 正式发布签名：只在环境变量齐备时注册（CI nightly 走这里；本地不注册，见文件顶部说明）。
        // 签名方案交给 AGP 按 minSdk 决定（minSdk 24 ⇒ v2 即可，不再显式开关 v1/v2，避免 API 变更踩坑）。
        if (releaseSigningReady) {
            create("release") {
                storeFile = releaseKeystorePath?.let { file(it) }
                storePassword = System.getenv("ZAYU_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ZAYU_KEY_ALIAS")
                keyPassword = System.getenv("ZAYU_KEY_PASSWORD")
            }
        }
        // 杂鱼Max 专属签名：读仓库外的 keystore.properties（见文件顶部说明），密钥本体不在仓库内。
        // 仅本地生效；源码包里没有这个文件 ⇒ 不注册，构建自动回退，不会因缺密钥而失败。
        if (localSigningReady) {
            localKeystoreProps?.let { props ->
                create("zayumax") {
                    storeFile = file(props.getProperty("storeFile"))
                    storePassword = props.getProperty("storePassword")
                    keyAlias = props.getProperty("keyAlias")
                    keyPassword = props.getProperty("keyPassword")
                }
            }
        }
    }

    buildTypes {
        debug {
            // 有杂鱼Max专属签名就用它；没有（别人拿到源码）则回退仓库自带 debug.keystore
            signingConfig = if (localSigningReady) {
                signingConfigs.getByName("zayumax")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        // Release 变体：R8 代码混淆 + 资源压缩瘦身（未使用的代码/资源裁剪）。
        // 签名：有发布证书就用正式签名（CI nightly / 本地自行导出变量），否则不签名 ⇒
        // 产物为 app-release-unsigned.apk（本地与 ci.yml 的编译校验都是这条路，不影响构建成功）。
        // R8 可能误删反射/序列化类，已在 proguard-rules.pro 补 Room 等 keep 规则。
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            // 优先级：CI 正式证书 > 杂鱼Max 专属本地签名 > 不签名（未签名产物）
            signingConfig = when {
                releaseSigningReady -> signingConfigs.getByName("release")
                localSigningReady -> signingConfigs.getByName("zayumax")
                else -> null
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        // 单元测试中 android.util.Log 等桩方法返回默认值（否则一调用就抛 "Stub!"）
        unitTests.isReturnDefaultValues = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget("17"))
        }
    }
}

